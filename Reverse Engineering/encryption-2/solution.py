# Secret data from GDB memory dump / 从 GDB 内存中获取的密文
secret = [
    0x31, 0x34, 0x36, 0x39, 0x31, 0x73, 0x2f, 0x32,
    0x2e, 0x71, 0x1d, 0x71, 0x2c, 0x21, 0x30, 0x3b,
    0x32, 0x36, 0x73, 0x72, 0x2c, 0x1d, 0x31, 0x21,
    0x2a, 0x71, 0x2f, 0x76, 0x3f
]

# XOR key found at 0x401143 / 在 0x401143 处找到的异或密钥
key = 0x42

# Decrypt by XORing each byte / 逐字节异或解密
flag = "".join([chr(b ^ key) for b in secret])

print(f"Flag: {flag}")
